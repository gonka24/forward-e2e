def wasm_abi_report(wasm_bytes: bytes = WASM_PLACEHOLDER, *, node: str = "v24.0.0") -> Dict[str, Any]:
    """The report ``scripts/test_wasm_query_boundary.mjs`` writes for a passing probe.

    ``observed`` is what the compiled ``ExternalQuerier`` decodes from each
    injected envelope: the parsed envelope itself for well-formed ones, and an
    ``invalid_response`` carrying the parser error plus the base64 of the raw
    envelope for the two malformed ones -- the exact assertions of the probe.
    """
    cases = []
    for name, envelope, expected_kind in WASM_CASES:
        if expected_kind == "invalid_response":
            observed: Any = {"error": {"invalid_response": {
                "error": WASM_PARSE_ERRORS[name],
                "response": base64.b64encode(envelope.encode("utf-8")).decode("ascii"),
            }}}
        else:
            observed = json.loads(envelope)
        cases.append({"name": name, "status": "PASS", "envelope": envelope,
                      "observed": observed, "query_chain_calls": 1})
    wasm_sha256 = hashlib.sha256(wasm_bytes).hexdigest()
    return canonical({
        "level": WASM_LEVEL,
        "wasm_sha256": wasm_sha256,
        "node": node,
        "status": "PASS",
        "cases": cases,
        "test_fixture_only": True,
        "synthetic_fixture": synthetic_block(
            WASM_DOCUMENT,
            producer="scripts/test_wasm_query_boundary.mjs",
            functions=("cases", "evidence"),
            purpose="9-case compiled-Wasm query_chain envelope decoding report bound to a placeholder Wasm artefact",
            producer_revision=WASM_PRODUCER_REVISION,
            producer_shape_note=WASM_PRODUCER_SHAPE_NOTE,
            extra={
                "bound_digests": [wasm_sha256],
                "bindings": {"wasm_sha256": "sha256 of the empty Wasm module 0061736d01000000 (never executed)"},
            },
        ),
    })


def go_test_events() -> List[Dict[str, Any]]:
    """``go test -json`` events for the two required tests, in Go's field order."""
    clock = [CLOCK_ORIGIN]

    def stamp() -> str:
        clock[0] = clock[0] + timedelta(milliseconds=1)
        return clock[0].strftime("%Y-%m-%dT%H:%M:%S.") + f"{clock[0].microsecond // 1000:03d}000000Z"

    def event(action: str, test: Optional[str] = None, **fields: Any) -> Dict[str, Any]:
        record: Dict[str, Any] = {"Time": stamp(), "Action": action, "Package": GO_PACKAGE}
        if test is not None:
            record["Test"] = test
        record.update(fields)
        return record

    def run_and_pass(test: str, children: Tuple[str, ...] = ()) -> List[Dict[str, Any]]:
        records = [event("run", test), event("output", test, Output=f"=== RUN   {test}\n")]
        for child in children:
            records.extend(run_and_pass(f"{test}/{child}"))
        records.append(event("output", test, Output=f"--- PASS: {test} (0.00s)\n"))
        records.append(event("pass", test, Elapsed=0))
        return records

    events = [event("start")]
    events.extend(run_and_pass(GO_REQUIRED_TESTS[0], GO_SYSTEM_ERROR_SUBTESTS))
    events.extend(run_and_pass(GO_REQUIRED_TESTS[1]))
    events.append(event("output", Output="PASS\n"))
    events.append(event("output", Output=f"ok  \t{GO_PACKAGE}\t0.010s\n"))
    events.append(event("pass", Elapsed=0.011))
    return events


def go_test_json_bytes() -> bytes:
    return "".join(json.dumps(record, separators=(",", ":")) + "\n" for record in go_test_events()).encode("utf-8")


