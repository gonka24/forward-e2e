BECH32_HRP = "gonka"
_BECH32_CHARSET = "qpzry9x8gf2tvdw0s3jn54khce6mua7l"


# ---------------------------------------------------------------------------
# derivations
# ---------------------------------------------------------------------------
def _digest(label: str) -> bytes:
    return hashlib.sha256(f"{SEED}:{label}".encode("utf-8")).digest()


def synthetic_hex(label: str, *, length: int = 64, upper: bool = False) -> str:
    """Hex digits derived from ``label``; ``length`` <= 64."""
    text = _digest(label).hex()[:length]
    return text.upper() if upper else text


def synthetic_tx_hash(document: str, ordinal: int) -> str:
    """Upper-case 64-hex transaction (or block/app) hash number ``ordinal`` of a document."""
    return synthetic_hex(f"{document}:tx:{ordinal}", upper=True)


def synthetic_sha256(document: str, ordinal: int) -> str:
    """Lower-case 64-hex content digest number ``ordinal`` of a document (code checksums, manifests)."""
    return synthetic_hex(f"{document}:sha256:{ordinal}")


def synthetic_hex40(document: str, ordinal: int, *, upper: bool = False) -> str:
    """40-hex identifier number ``ordinal`` (node IDs, validator addresses, non-pinned Git SHAs)."""
    return synthetic_hex(f"{document}:hex40:{ordinal}", length=40, upper=upper)


def synthetic_pubkey(document: str, label: str) -> str:
    """Base64 of 32 derived bytes, the shape of a Tendermint Ed25519 public key."""
    return base64.b64encode(_digest(f"{document}:pubkey:{label}")).decode("ascii")


def synthetic_timestamp(ordinal: int, *, nanoseconds: bool = False) -> str:
    """``ordinal`` minutes after the synthetic clock origin, RFC 3339 with ``Z``."""
    moment = CLOCK_ORIGIN + timedelta(minutes=ordinal)
    text = moment.strftime("%Y-%m-%dT%H:%M:%S")
    return text + (".000000000Z" if nanoseconds else "Z")


def synthetic_run_id(document: str) -> str:
    return f"synthetic-{document}"


def _bech32_polymod(values: List[int]) -> int:
    generator = (0x3B6A57B2, 0x26508E6D, 0x1EA119FA, 0x3D4233DD, 0x2A1462B3)
    checksum = 1
    for value in values:
        top = checksum >> 25
        checksum = ((checksum & 0x1FFFFFF) << 5) ^ value
        for index in range(5):
            checksum ^= generator[index] if ((top >> index) & 1) else 0
    return checksum


def _bech32_hrp_expand(hrp: str) -> List[int]:
    return [ord(c) >> 5 for c in hrp] + [0] + [ord(c) & 31 for c in hrp]


def _bech32_create_checksum(hrp: str, data: List[int]) -> List[int]:
    values = _bech32_hrp_expand(hrp) + data
    polymod = _bech32_polymod(values + [0, 0, 0, 0, 0, 0]) ^ 1
    return [(polymod >> 5 * (5 - index)) & 31 for index in range(6)]


def _convert_bits(data: bytes, from_bits: int, to_bits: int) -> List[int]:
    accumulator = 0
    bits = 0
    result: List[int] = []
    max_value = (1 << to_bits) - 1
    for value in data:
        accumulator = (accumulator << from_bits) | value
        bits += from_bits
        while bits >= to_bits:
            bits -= to_bits
            result.append((accumulator >> bits) & max_value)
    if bits:
        result.append((accumulator << (to_bits - bits)) & max_value)
    return result


def bech32_encode(hrp: str, payload: bytes) -> str:
    """Standard Bech32 (BIP-173) encoding, as Cosmos SDK addresses use."""
    data = _convert_bits(payload, 8, 5)
    combined = data + _bech32_create_checksum(hrp, data)
    return hrp + "1" + "".join(_BECH32_CHARSET[d] for d in combined)


def synthetic_address(document: str, role: str, *, contract: bool = False) -> str:
    """A valid Bech32 ``gonka1...`` address derived from the document and role.

    Accounts are 20-byte payloads (44 characters), CosmWasm contracts 32-byte
    payloads (64 characters), exactly as the chain renders them, so the
    documents keep the producer's string lengths.
    """
    size = 32 if contract else 20
    return bech32_encode(BECH32_HRP, _digest(f"{document}:address:{role}")[:size])


