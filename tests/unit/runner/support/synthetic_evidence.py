"""Deterministic synthetic chain identities and generated boundary fixtures.

Why this module exists
----------------------
The committed documents under ``tests/fixtures/evidence/`` must be
*producer-shaped* (so the real verifier code paths are exercised) and at the
same time carry *no identity of any recorded run* (so nothing in the
repository can be presented as, or quietly depend on, a development receipt).
Those two requirements meet in the chain identities: addresses, transaction
hashes, code checksums, block hashes, node IDs, validator keys and
timestamps. This module is the single definition of how a synthetic identity
is derived, so that

* the committed fixtures can be checked -- not merely asserted -- to contain
  only synthetic identities (``identity_findings`` below, used by
  ``tests/unit/runner/test_synthetic_evidence.py``), and
* the two boundary fixtures (Go query-error classification and the Wasm
  ``query_chain`` ABI report) are regenerated byte-for-byte from code
  (``boundary_fixture_files``), which the same test pins against the files on
  disk.

Two kinds of document share that contract and must not be confused:

* The four live-context documents are *identity-scrubbed derivations of
  former development receipts*. ``renumber_identities`` replaced every
  address, transaction and block hash, code checksum, node id, validator
  public key, timestamp, run id, host path and run label with a seed
  derivation; the recorded economic arithmetic (amounts, heights, epochs,
  gas, balances, runtime versions, event attributes) was deliberately kept so
  the verifier's cross-field rules still meet producer-shaped numbers. They
  therefore retain a partial regression on recorded *arithmetic shape* and
  none on recorded *identities*; they are never live receipts.
* The Go and Wasm boundary fixtures are generated by ``boundary_fixture_files``
  from the constants in this module; no value in them was ever recorded.

Every derivation is ``SHA-256(SEED + ":" + label)``; the label names the
document and the role or ordinal of the identity. Nothing here reads a chain,
Docker, Git history or any recorded document.

All fixtures are synthetic. No network, Docker, or live chain calls.
"""

